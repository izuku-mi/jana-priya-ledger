export type Key = keyof typeof DICT;

@Injectable({ providedIn: 'root' })
export class I18n {
  private store = inject(LedgerStore);
  readonly lang = computed(() => this.store.settings().lang);
  readonly isTe = computed(() => this.lang() === 'te');

  t(key: Key): string {
    return DICT[key][this.isTe() ? 1 : 0];
  }

  /** Brand name in the current language. */
  name(x: { nameEn: string; nameTe: string }) {
    return this.isTe() ? x.nameTe || x.nameEn : x.nameEn;
  }

  /** Inline text pair when a sentence is built from data. */
  pick(en: string, te: string) {
    return this.isTe() ? te : en;
  }
}
